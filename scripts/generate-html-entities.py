#!/usr/bin/env python3
"""Generates Sources/MermaidLayout/HTMLEntities.swift from WHATWG's entities.json.

    curl -sSfLO https://html.spec.whatwg.org/entities.json
    scripts/generate-html-entities.py entities.json > Sources/MermaidLayout/HTMLEntities.swift

Every named character reference HTML defines: those ending in `;`, and the
legacy ones a browser also reads without it (`&amp`, `&copy`…).
"""
import hashlib
import json
import sys

raw = open(sys.argv[1], 'rb').read()
table = json.loads(raw)
lines = []
for key in sorted(table):
    assert key.startswith('&') and ' ' not in key
    points = ' '.join(f'{p:X}' for p in table[key]['codepoints'])
    lines.append(f'{key[1:]} {points}')

print(f'''// Generated by scripts/generate-html-entities.py; don't edit.
// Source: https://html.spec.whatwg.org/entities.json
// sha256 {hashlib.sha256(raw).hexdigest()}, {len(table)} names.

extension MermaidParser {{
    /// HTML's named character references, by name without the `&`: a name
    /// ending in `;`, or a legacy one read without it. Each maps to its text.
    static let htmlEntities: [String: String] = {{
        var table: [String: String] = [:]
        for line in htmlEntityLines.split(separator: "\\n") {{
            let fields = line.split(separator: " ")
            table[String(fields[0])] = String(String.UnicodeScalarView(
                fields.dropFirst().compactMap {{ UInt32($0, radix: 16).flatMap(Unicode.Scalar.init) }}))
        }}
        return table
    }}()

    /// The longest name in `htmlEntities`.
    static let htmlEntityMaxLength = {max(len(k) - 1 for k in table)}

    private static let htmlEntityLines = """
{chr(10).join(lines)}
"""
}}''')
